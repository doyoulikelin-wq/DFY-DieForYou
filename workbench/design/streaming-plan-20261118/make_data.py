def ev(at, lane, node, typ, text, payload=None, delivery=None, delivery_id=None):
    d=dict(at=at,lane=lane,node=node,type=typ,text=text,payload=payload or {})
    if delivery is not None: d.update(delivery_text=delivery,delivery_id=delivery_id or 'answer-1')
    return d

def seg(node,lane,label,start,end):
    return dict(node=node,lane=lane,label=label,start=start,end=end)

